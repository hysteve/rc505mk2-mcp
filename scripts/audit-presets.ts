/**
 * Static audit of bundled + user presets against PARAM_MAP and the transforms.
 *
 *   npx tsx scripts/audit-presets.ts                       # report, exit 1 if any bundled preset has issues
 *   npx tsx scripts/audit-presets.ts --markdown <file>     # also write the preset catalog
 *   npx tsx scripts/audit-presets.ts --all                 # exit 1 on user-preset issues too
 *
 * Reports params that the generator would silently drop, coerce, mis-index, or clamp.
 */
import { join, dirname } from 'node:path';
import { writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { loadBundledRacks } from '../src/data/load-racks.js';
import { FxModuleStore } from '../src/mcp/fx-module-store.js';
import { RackStore } from '../src/stores/rack-store.js';
import { resolveUserRacksDir } from '../src/stores/paths.js';
import { validateSlotParams, type ParamIssue } from '../src/params/validate-params.js';
import type { Rack, FxSlotData } from '../src/schemas/rack.js';
import type { FxModule } from '../src/schemas/fx-module.js';

type Row = { preset: string; where: string; issue: ParamIssue };

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const mdIdx = args.indexOf('--markdown');
const markdownPath = mdIdx !== -1 ? args[mdIdx + 1] : undefined;
const strictAll = args.includes('--all');

const modules = new FxModuleStore(join(root, 'data', 'fx-modules')).loadAll().sort((a, b) => a.id.localeCompare(b.id));
const moduleIds = new Set(modules.map(m => m.id));
const bundledRacks = loadBundledRacks();
const userRacks = existsSync(resolveUserRacksDir()) ? new RackStore().loadAll() : [];

const rows: Row[] = [];

function auditSlot(preset: string, ctx: 'ifx' | 'tfx', s: FxSlotData) {
  const where = `${ctx}${s.bank ? ' ' + s.bank : ''}/${s.slot} ${s.effect}`;
  if (s.fxModuleId && !moduleIds.has(s.fxModuleId)) {
    rows.push({ preset, where, issue: { level: 'error', kind: 'unknown-effect', value: s.fxModuleId, outcome: 'module missing', message: `fxModuleId "${s.fxModuleId}" not found` } });
  }
  const { issues } = validateSlotParams(s.effect, [...s.params, ...(s.overrides ?? [])]);
  for (const issue of issues) rows.push({ preset, where, issue });
}
function auditRack(prefix: string, r: Rack) {
  for (const s of r.inputFx) auditSlot(`${prefix}:${r.id}`, 'ifx', s);
  for (const s of r.trackFx) auditSlot(`${prefix}:${r.id}`, 'tfx', s);
}
function auditModule(m: FxModule) {
  const { issues } = validateSlotParams(m.effect, m.params);
  for (const issue of issues) rows.push({ preset: `module:${m.id}`, where: m.effect, issue });
}

for (const m of modules) auditModule(m);
for (const r of bundledRacks) auditRack('rack', r);
for (const r of userRacks) auditRack('user', r);

// ── Report ────────────────────────────────────────────────────────────
const byKind: Record<string, number> = {};
for (const r of rows) byKind[r.issue.kind] = (byKind[r.issue.kind] ?? 0) + 1;
const affected = new Set(rows.map(r => r.preset));
const count = (prefix: string) => [...affected].filter(p => p.startsWith(prefix)).length;

console.log('BY KIND', byKind);
console.log(`affected modules: ${count('module:')} / ${modules.length}`);
console.log(`affected bundled racks: ${count('rack:')} / ${bundledRacks.length}`);
console.log(`affected user racks: ${count('user:')} / ${userRacks.length}`);
console.log('\n--- DETAIL ---');
for (const r of rows) console.log(`${r.preset} | ${r.where} | ${r.issue.kind} | ${r.issue.message} → ${r.issue.outcome}${r.issue.suggestion ? ` (did you mean ${r.issue.suggestion}?)` : ''}`);

// ── Markdown catalog ──────────────────────────────────────────────────
if (markdownPath) {
  const counts = (preset: string) => {
    const c: Record<string, number> = {};
    for (const r of rows) if (r.preset === preset) c[r.issue.kind] = (c[r.issue.kind] ?? 0) + 1;
    return Object.entries(c).sort().map(([k, v]) => `${v} ${k}`).join(', ') || '—';
  };
  const today = new Date().toISOString().slice(0, 10);
  const out: string[] = [];
  out.push(`# Preset Catalog — audit snapshot (${today})\n`);
  out.push('Generated by `npm run catalog:presets` from a static audit of every bundled rack, bundled FX module, and local user rack against the current `PARAM_MAP` and transforms. **No preset in this catalog has been verified on hardware.** Every row starts at `untested`.\n');
  out.push('Issue kinds:\n');
  out.push('- **unknown-param** — name not in `PARAM_MAP` for that effect; the generator skips it (device keeps the template default).');
  out.push('- **unrecognized-value** — value not accepted by the transform; falls back to a numeric parse (usually `0`).');
  out.push('- **enum-index** — a plain number given for an enum param (e.g. `LOW CUT: 20`); used as the enum index, not as Hz.');
  out.push('- **out-of-range** — numeric value outside the transform range; written at the clamp boundary.');
  out.push('- **unsupported-note-value** — tempo-synced RATE value; encoding pending device verification.');
  out.push('- **unknown-effect** — effect name (or fxModuleId) not resolvable; the whole slot is skipped.\n');
  out.push(`**Totals:** ${count('rack:')}/${bundledRacks.length} bundled racks, ${count('module:')}/${modules.length} bundled modules, ${count('user:')}/${userRacks.length} local user racks affected. By kind: ${Object.entries(byKind).sort().map(([k, v]) => `${v} ${k}`).join(', ') || 'none'}.\n`);
  out.push(`## Bundled racks (${bundledRacks.length})\n`);
  out.push('| # | id | title | section | IFX | TFX (banks) | effects | issues | status |');
  out.push('|---|----|-------|---------|-----|-------------|---------|--------|--------|');
  bundledRacks.forEach((r, i) => {
    const banks = [...new Set(r.trackFx.map(s => s.bank ?? '?'))].sort();
    const effects = [...new Set([...r.inputFx, ...r.trackFx].map(s => s.effect))].join(', ');
    out.push(`| ${i + 1} | \`${r.id}\` | ${r.title} | ${r.section} | ${r.inputFx.length} | ${r.trackFx.length} (${banks.join('/') || '—'}) | ${effects} | ${counts('rack:' + r.id)} | untested |`);
  });
  out.push(`\n## Bundled FX modules (${modules.length})\n`);
  out.push('| # | id | effect | context | usage | params | issues | status |');
  out.push('|---|----|--------|---------|-------|--------|--------|--------|');
  modules.forEach((m, i) => out.push(`| ${i + 1} | \`${m.id}\` | ${m.effect} | ${m.context.join('/')} | ${m.usage} | ${m.params.length} | ${counts('module:' + m.id)} | untested |`));
  out.push(`\n## Local user racks (\`~/.rc505mk2/racks/\`, ${userRacks.length})\n`);
  out.push('| id | IFX | TFX | module refs | issues |');
  out.push('|----|-----|-----|-------------|--------|');
  for (const r of userRacks) out.push(`| \`${r.id}\` | ${r.inputFx.length} | ${r.trackFx.length} | ${[...r.inputFx, ...r.trackFx].filter(s => s.fxModuleId).length} | ${counts('user:' + r.id)} |`);
  out.push('\n## Issue detail\n');
  for (const preset of [...affected].sort()) {
    out.push(`### ${preset}\n`);
    for (const r of rows.filter(x => x.preset === preset)) out.push(`- ${r.where}: ${r.issue.message} → ${r.issue.outcome}${r.issue.suggestion ? ` (did you mean \`${r.issue.suggestion}\`?)` : ''}`);
    out.push('');
  }
  writeFileSync(markdownPath, out.join('\n') + '\n');
  console.log(`\nwrote ${markdownPath}`);
}

const failing = rows.filter(r => strictAll || !r.preset.startsWith('user:'));
process.exit(failing.length ? 1 : 0);
